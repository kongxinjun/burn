//! Standalone reproductions: a case written as a Rust crate that uses only Burn's public API, runs
//! the failing program on the device and on Flex, and prints how they differ.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use burn::tensor::FloatDType;

use crate::program::{
    Binary, Input, Op, Program, Reduce, Reference, Unary, cycle, output_shape, pattern,
    pattern_scale, round_to,
};
use crate::session::Case;

/// Which inputs the runs of a program use.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Inputs {
    Main,
    Resized,
    Both,
}

impl Inputs {
    fn of(case: &Case, program: usize) -> Self {
        let runs = case.runs.iter().filter(|run| run.program == program);
        match (
            runs.clone().any(|run| !run.resized),
            runs.clone().any(|run| run.resized),
        ) {
            (true, true) => Self::Both,
            (false, true) => Self::Resized,
            _ => Self::Main,
        }
    }
}

/// Writes the reproduction of `case` to `out` as a crate depending on the Burn checkout at `burn`.
/// A case that needs the autotune results of `environment` ships a copy of it and runs in it.
pub(crate) fn emit(case: &Case, environment: Option<&Path>, burn: &Path, out: &Path) {
    let programs = case.programs();
    let last = *case.runs.last().expect("Cases have a run");
    let target = &programs[last.program];
    let input = match last.resized {
        true => target.resized.as_ref().expect("Resized runs have an input"),
        false => &target.input,
    };
    let slack = Reference::compute(target, input).map_or(0.0, |reference| reference.slack);

    let mut writer = Writer::default();
    let mut functions = String::new();
    let used = case
        .runs
        .iter()
        .map(|run| run.program)
        .collect::<BTreeSet<_>>();
    for &index in &used {
        let eager = case
            .runs
            .iter()
            .any(|run| run.program == index && run.eager);
        functions += &writer.program(index, &programs[index], Inputs::of(case, index), eager);
    }

    let (backend, fusion) = case
        .backend
        .split_once('+')
        .map_or((case.backend.as_str(), false), |(backend, _)| {
            (backend, true)
        });
    let device = match backend {
        "metal" => "Device::metal()",
        "cuda" => "Device::cuda(0)",
        "wgpu" => "Device::wgpu(Default::default())",
        "cpu" => "Device::cpu()",
        other => panic!("No device for backend {other}"),
    };
    let call = |run: &crate::session::Run, device: &str, dtype: FloatDType| {
        let mut arguments = vec![device.to_string(), dtype_expr(dtype)];
        if Inputs::of(case, run.program) == Inputs::Both {
            arguments.push(run.resized.to_string());
        }
        if case
            .runs
            .iter()
            .any(|other| other.program == run.program && other.eager)
        {
            arguments.push(run.eager.to_string());
        }
        format!("program_{}({})", run.program, arguments.join(", "))
    };

    let mut main = String::new();
    writeln!(main, "fn main() {{").unwrap();
    if environment.is_some() {
        writeln!(main, "    use_environment();").unwrap();
    }
    writeln!(main, "    let device = {device};").unwrap();
    writeln!(main, "    let flex = Device::flex();").unwrap();
    let (last, history) = case.runs.split_last().expect("Cases have a run");
    if !history.is_empty() {
        writeln!(
            main,
            "\n    // Earlier runs, which leave the device in the state the failure needs."
        )
        .unwrap();
        for run in history {
            let dtype = programs[run.program].dtype;
            writeln!(main, "    {};", call(run, "&device", dtype)).unwrap();
        }
        writeln!(main).unwrap();
    }
    writeln!(
        main,
        "    let actual = {};",
        call(last, "&device", target.dtype)
    )
    .unwrap();
    writeln!(
        main,
        "    let expected = {};",
        call(
            &crate::session::Run {
                eager: false,
                ..*last
            },
            "&flex",
            FloatDType::F32
        )
    )
    .unwrap();
    writeln!(main, "    compare(&actual, &expected, {slack:?});").unwrap();
    writeln!(main, "}}").unwrap();

    let mut source = String::new();
    writeln!(
        source,
        "//! {} with {}: the last run differs from Flex computing in f32.\n//! Generated by lab-fuzz from a reduced case.\n",
        case.backend,
        crate::program::dtype_name(target.dtype)
    )
    .unwrap();
    source += &writer.imports();
    source += "\n";
    source += &main;
    source += &functions;
    source += &writer.helpers();
    if environment.is_some() {
        source += USE_ENVIRONMENT;
    }
    source += COMPARE;

    let mut features = vec!["std", "flex", "autotune", "rayon", "simd", backend];
    if fusion {
        features.push("fusion");
    }
    if environment.is_some() {
        features.push("cubecl");
    }
    let manifest = format!(
        r#"[package]
name = "lab-repro"
version = "0.1.0"
edition = "2024"
publish = false

[dependencies]
burn = {{ path = "{}", default-features = false, features = [{}] }}

[workspace]
"#,
        burn.join("crates/burn").display(),
        features
            .iter()
            .map(|feature| format!("\"{feature}\""))
            .collect::<Vec<_>>()
            .join(", ")
    );

    std::fs::create_dir_all(out.join("src")).expect("The reproduction should be writable");
    std::fs::write(out.join("Cargo.toml"), manifest).expect("The manifest should be writable");
    std::fs::write(out.join("src/main.rs"), source).expect("The source should be writable");
    if let Some(environment) = environment {
        let copy = out.join("environment");
        std::fs::create_dir_all(&copy).expect("The environment should be writable");
        for entry in std::fs::read_dir(environment).expect("The environment should be readable") {
            let path = entry.expect("Environment entries are readable").path();
            if path.is_file() && !path.to_string_lossy().ends_with("-shm") {
                let name = path.file_name().expect("Files have names");
                std::fs::copy(&path, copy.join(name)).expect("The environment should copy");
            }
        }
    }
    if !writer.files.is_empty() {
        std::fs::create_dir_all(out.join("data")).expect("The data should be writable");
        for (name, bytes) in &writer.files {
            std::fs::write(out.join("data").join(name), bytes).expect("Data should be writable");
        }
    }
}

const USE_ENVIRONMENT: &str = r#"
/// Makes CubeCL use the autotune results in `environment/`, which the failure needs, instead of
/// tuning again. Must run before the device is first used.
fn use_environment() {
    use burn::cubecl::config::cache::CacheConfig;
    use burn::cubecl::config::{CubeClRuntimeConfig, RuntimeConfig};

    let mut config = CubeClRuntimeConfig::default();
    let directory = concat!(env!("CARGO_MANIFEST_DIR"), "/environment");
    config.environment.path = CacheConfig::Directory(directory.into());
    CubeClRuntimeConfig::set(config);
}
"#;

const COMPARE: &str = r#"
/// Compares like lab-fuzz: NaN matches NaN, and errors scale with the largest finite value.
fn compare(actual: &[f32], expected: &[f32], slack: f32) {
    assert_eq!(actual.len(), expected.len(), "The outputs differ in size");
    let scale = expected
        .iter()
        .filter(|value| value.is_finite())
        .fold(1.0f32, |largest, value| largest.max(value.abs()));
    let wrong = (0..expected.len())
        .filter(|&i| {
            let (a, e) = (actual[i], expected[i]);
            match (a.is_nan(), e.is_nan()) {
                (true, true) => false,
                (true, false) | (false, true) => true,
                _ if a.is_infinite() || e.is_infinite() => a != e,
                _ => (a - e).abs() > slack + 2e-3 * scale + 2e-3 * e.abs(),
            }
        })
        .collect::<Vec<_>>();
    for &i in wrong.iter().take(5) {
        println!("element {i}: {} instead of {}", actual[i], expected[i]);
    }
    println!("{} of {} elements differ from Flex", wrong.len(), expected.len());
}
"#;

fn dtype_expr(dtype: FloatDType) -> String {
    match dtype {
        FloatDType::F16 => "DType::F16",
        FloatDType::BF16 => "DType::BF16",
        _ => "DType::F32",
    }
    .to_string()
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Helper {
    Float,
    Pattern,
    Cycle,
    FloatFile,
    IndexFile,
}

/// Accumulates the imports, helpers and data files the emitted functions need.
#[derive(Default)]
struct Writer {
    imports: BTreeMap<&'static str, BTreeSet<&'static str>>,
    helpers: BTreeSet<Helper>,
    files: Vec<(String, Vec<u8>)>,
}

impl Writer {
    fn import(&mut self, module: &'static str, name: &'static str) {
        self.imports.entry(module).or_default().insert(name);
    }

    fn imports(&mut self) -> String {
        self.import("burn::tensor", "DType");
        self.import("burn::tensor", "Device");
        self.import("burn::tensor", "Tensor");
        self.imports
            .iter()
            .map(|(module, names)| {
                let names = names.iter().copied().collect::<Vec<_>>();
                match names.as_slice() {
                    [name] => format!("use {module}::{name};\n"),
                    names => format!("use {module}::{{{}}};\n", names.join(", ")),
                }
            })
            .collect()
    }

    fn helpers(&self) -> String {
        let mut source = String::new();
        for helper in &self.helpers {
            source += match helper {
                Helper::Float => {
                    r#"
fn float<const D: usize>(values: Vec<f32>, shape: [usize; D], device: &Device, dtype: DType) -> Tensor<D> {
    Tensor::from_data(TensorData::new(values, shape), (device, dtype))
}
"#
                }
                Helper::Pattern => {
                    r#"
/// Deterministic values in `[-scale, scale]`.
fn pattern(count: usize, salt: usize, scale: f32) -> Vec<f32> {
    (0..count)
        .map(|i| (((i * 37 + salt * 101) % 199) as f32 / 99.0 - 1.0) * scale)
        .collect()
}
"#
                }
                Helper::Cycle => {
                    r#"
/// The indices `0, 1, .., bound - 1, 0, 1, ..`.
fn cycle(count: usize, bound: usize) -> Vec<i64> {
    (0..count).map(|i| (i % bound) as i64).collect()
}
"#
                }
                Helper::FloatFile => {
                    r#"
fn floats(bytes: &[u8]) -> Vec<f32> {
    bytes.chunks_exact(4).map(|b| f32::from_le_bytes(b.try_into().unwrap())).collect()
}
"#
                }
                Helper::IndexFile => {
                    r#"
fn indices(bytes: &[u8]) -> Vec<i64> {
    bytes.chunks_exact(8).map(|b| i64::from_le_bytes(b.try_into().unwrap())).collect()
}
"#
                }
            };
        }
        source
    }

    /// The expression of `values`, a pattern when they are one.
    fn floats(&mut self, values: &[f32], salt: usize, dtype: FloatDType) -> String {
        let scale = pattern_scale(values);
        let patterned = pattern(values.len(), salt, scale)
            .into_iter()
            .map(|value| round_to(dtype, value));
        if patterned.eq(values.iter().copied()) {
            self.helpers.insert(Helper::Pattern);
            return format!("pattern({}, {salt}, {scale:?})", values.len());
        }
        if values.len() <= 32 {
            let literals = values.iter().map(|v| format!("{v:?}")).collect::<Vec<_>>();
            return format!("vec![{}]", literals.join(", "));
        }
        self.helpers.insert(Helper::FloatFile);
        let name = format!("values{}.bin", self.files.len());
        let bytes = values.iter().flat_map(|v| v.to_le_bytes()).collect();
        self.files.push((name.clone(), bytes));
        format!("floats(include_bytes!(\"../data/{name}\"))")
    }

    fn indices(&mut self, indices: &[i64], bound: usize) -> String {
        if indices == cycle(indices.len(), bound).as_slice() {
            self.helpers.insert(Helper::Cycle);
            return format!("cycle({}, {bound})", indices.len());
        }
        if indices.len() <= 32 {
            let literals = indices.iter().map(|i| format!("{i}")).collect::<Vec<_>>();
            return format!("vec![{}i64]", literals.join(", "));
        }
        self.helpers.insert(Helper::IndexFile);
        let name = format!("indices{}.bin", self.files.len());
        let bytes = indices.iter().flat_map(|i| i.to_le_bytes()).collect();
        self.files.push((name.clone(), bytes));
        format!("indices(include_bytes!(\"../data/{name}\"))")
    }

    fn tensor(
        &mut self,
        values: &[f32],
        salt: usize,
        dtype: FloatDType,
        shape: &[usize],
    ) -> String {
        self.helpers.insert(Helper::Float);
        self.import("burn::tensor", "TensorData");
        let values = self.floats(values, salt, dtype);
        format!("float({values}, {shape:?}, device, dtype)")
    }

    /// `program_<index>`: runs the program on a device in a dtype and returns its outputs.
    fn program(&mut self, index: usize, program: &Program, inputs: Inputs, eager: bool) -> String {
        self.helpers.insert(Helper::Float);
        self.import("burn::tensor", "TensorData");
        let mut parameters = vec!["device: &Device", "dtype: DType"];
        if inputs == Inputs::Both {
            parameters.push("resized: bool");
        }
        if eager {
            parameters.push("eager: bool");
        }
        let mut body = String::new();
        let input = |writer: &mut Self, input: &Input, salt| {
            let values = writer.floats(&input.data, salt, program.dtype);
            format!("float({values}, {:?}, device, dtype)", input.shape)
        };
        let resized = program.resized.as_ref();
        match inputs {
            Inputs::Main => {
                let main = input(self, &program.input, 0);
                writeln!(body, "    let mut x = {main};").unwrap();
            }
            Inputs::Resized => {
                let other = input(self, resized.expect("Resized runs have an input"), 1);
                writeln!(body, "    let mut x = {other};").unwrap();
            }
            Inputs::Both => {
                let main = input(self, &program.input, 0);
                let other = input(self, resized.expect("Resized runs have an input"), 1);
                writeln!(
                    body,
                    "    let mut x = match resized {{\n        true => {other},\n        false => {main},\n    }};"
                )
                .unwrap();
            }
        }
        if eager {
            writeln!(
                body,
                "    // Eager runs wait for the device after every operation.\n    let sync = |x: Tensor<4>| {{\n        if eager {{\n            device.sync().unwrap();\n        }}\n        x\n    }};"
            )
            .unwrap();
        }

        // Constants are shaped by the main input; the other only changes the batch.
        let mut shape = program.input.shape;
        for (position, op) in program.ops.iter().enumerate() {
            let expression = self.operation(op, shape, 2 + 2 * position, program.dtype);
            match eager {
                true => writeln!(body, "    x = sync({expression});").unwrap(),
                false => writeln!(body, "    x = {expression};").unwrap(),
            }
            shape = output_shape(op, shape).expect("Valid programs have an output shape");
        }
        writeln!(
            body,
            "    x.into_data().convert::<f32>().try_into_vec::<f32>().unwrap()"
        )
        .unwrap();
        format!(
            "\nfn program_{index}({}) -> Vec<f32> {{\n{body}}}\n",
            parameters.join(", ")
        )
    }

    fn unary(&mut self, op: Unary, x: &str) -> String {
        let mut activation = |name: &'static str| {
            self.import("burn::tensor::activation", name);
            format!("{name}({x})")
        };
        match op {
            Unary::Relu => activation("relu"),
            Unary::Sigmoid => activation("sigmoid"),
            Unary::Tanh => activation("tanh"),
            Unary::Gelu => activation("gelu"),
            Unary::Silu => activation("silu"),
            Unary::Abs => format!("{x}.abs()"),
            Unary::Neg => format!("{x}.neg()"),
            Unary::Sin => format!("{x}.sin()"),
            Unary::Exp => format!("{x}.clamp(-4.0, 4.0).exp()"),
            Unary::Log1pAbs => format!("({x}.abs() + 1.0).log()"),
            Unary::SqrtAbs => format!("({x}.abs() + 1e-3).sqrt()"),
            Unary::Square => format!("{x}.powi_scalar(2) * 0.5"),
        }
    }

    fn binary(op: Binary, x: &str, y: &str) -> String {
        match op {
            Binary::Add => format!("{x} + {y}"),
            Binary::Sub => format!("{x} - {y}"),
            Binary::Mul => format!("{x} * {y}"),
            Binary::Max => format!("{x}.max_pair({y})"),
            Binary::Min => format!("{x}.min_pair({y})"),
            Binary::SafeDiv => format!("{x} / ({y}.abs() + 1.0)"),
        }
    }

    /// The expression of `op` applied to `x`, which has `shape` on the main input.
    fn operation(&mut self, op: &Op, shape: [usize; 4], salt: usize, dtype: FloatDType) -> String {
        match op {
            Op::Unary(op) => self.unary(*op, "x"),
            Op::Scalar { op, value } => Self::binary(
                *op,
                "x",
                &format!("Tensor::<4>::full([1, 1, 1, 1], {value:?}, (device, dtype))"),
            ),
            Op::Broadcast {
                op,
                shape: other,
                data,
            } => {
                let y = self.tensor(data, salt, dtype, other);
                Self::binary(*op, "x", &y)
            }
            Op::Conv {
                channels_out,
                kernel,
                stride,
                padding,
                dilation,
                groups,
                weight,
                bias,
            } => {
                self.import("burn::tensor::module", "conv2d");
                self.import("burn::tensor::ops", "ConvOptions");
                let weight_shape = [*channels_out, shape[1] / groups, kernel[0], kernel[1]];
                let weight = self.tensor(weight, salt, dtype, &weight_shape);
                let bias = match bias {
                    Some(bias) => format!(
                        "Some({})",
                        self.tensor(bias, salt + 1, dtype, &[*channels_out])
                    ),
                    None => "None".to_string(),
                };
                format!(
                    "conv2d(x, {weight}, {bias}, ConvOptions::new([{stride}; 2], [{padding}; 2], [{dilation}; 2], {groups}))"
                )
            }
            Op::MaxPool {
                kernel,
                stride,
                padding,
                dilation,
                ceil,
            } => {
                self.import("burn::tensor::module", "max_pool2d");
                self.import("burn::tensor::ops", "MaxPoolOptions");
                format!(
                    "max_pool2d(x, MaxPoolOptions::new([{kernel}; 2]).with_stride([{stride}; 2]).with_padding([{padding}; 2]).with_dilation([{dilation}; 2]).with_ceil_mode({ceil}))"
                )
            }
            Op::AvgPool {
                kernel,
                stride,
                padding,
                count_include_pad,
                ceil,
            } => {
                self.import("burn::tensor::module", "avg_pool2d");
                self.import("burn::tensor::ops", "AvgPoolOptions");
                format!(
                    "{{\n        let mut options = AvgPoolOptions::new([{kernel}; 2]).with_stride([{stride}; 2]).with_padding([{padding}; 2]);\n        options.count_include_pad = {count_include_pad};\n        options.ceil_mode = {ceil};\n        avg_pool2d(x, options)\n    }}"
                )
            }
            Op::AdaptiveAvgPool { size } => {
                self.import("burn::tensor::module", "adaptive_avg_pool2d");
                format!("adaptive_avg_pool2d(x, {size:?})")
            }
            Op::Interpolate { mode, size } => {
                self.import("burn::tensor::module", "interpolate");
                self.import("burn::tensor::module", "InterpolateMode");
                self.import("burn::tensor::module", "InterpolateOptions");
                let mode = match mode {
                    0 => "InterpolateMode::Nearest".to_string(),
                    1 | 2 => {
                        self.import("burn::tensor::module", "CoordinateTransformMode");
                        let transform = if *mode == 1 {
                            "HalfPixel"
                        } else {
                            "AlignCorners"
                        };
                        format!(
                            "InterpolateMode::Bilinear {{ coordinate_transform: CoordinateTransformMode::{transform} }}"
                        )
                    }
                    _ => {
                        self.import("burn::tensor::module", "CoordinateTransformMode");
                        "InterpolateMode::Bicubic { coordinate_transform: CoordinateTransformMode::HalfPixel, a: -0.75 }".to_string()
                    }
                };
                format!(
                    "interpolate(x, InterpolateOptions::new({mode}).with_output_size({size:?}))"
                )
            }
            Op::Permute(axes) => format!("x.permute({axes:?})"),
            Op::Flip(axis) => format!("x.flip([{axis}])"),
            Op::Narrow { dim, start, length } => format!("x.narrow({dim}, {start}, {length})"),
            Op::CatWithItself { dim, other } => {
                let other = self.unary(*other, "x.clone()");
                format!("Tensor::cat(vec![x.clone(), {other}], {dim})")
            }
            Op::Repeat { dim, times } => format!("x.repeat_dim({dim}, {times})"),
            Op::Reduce { op, dim } => {
                let name = match op {
                    Reduce::Sum => "sum_dim",
                    Reduce::Mean => "mean_dim",
                    Reduce::Max => "max_dim",
                    Reduce::Min => "min_dim",
                };
                format!("x.{name}({dim})")
            }
            Op::Softmax { dim, log } => {
                let name = if *log { "log_softmax" } else { "softmax" };
                self.import("burn::tensor::activation", name);
                format!("{name}(x, {dim})")
            }
            Op::Matmul {
                shape: other, data, ..
            } => format!("x.matmul({})", self.tensor(data, salt, dtype, other)),
            Op::Normalize { dim } => format!(
                "{{\n        let centered = x.clone() - x.mean_dim({dim});\n        let variance = centered.clone().powi_scalar(2).mean_dim({dim});\n        centered / (variance + 1e-5).sqrt()\n    }}"
            ),
            Op::MaskFill { threshold, value } => format!(
                "{{\n        let mask = x.clone().greater_elem({threshold:?});\n        x.mask_fill(mask, {value:?})\n    }}"
            ),
            Op::Clamp { min, max } => format!("x.clamp({min:?}, {max:?})"),
            Op::Select { dim, indices } => {
                self.import("burn::tensor", "Int");
                self.import("burn::tensor", "TensorData");
                let values = self.indices(indices, shape[*dim]);
                format!(
                    "x.select({dim}, Tensor::<1, Int>::from_data(TensorData::new({values}, [{}]), device))",
                    indices.len()
                )
            }
            Op::Gather {
                dim,
                shape: gathered,
                indices,
            } => {
                self.import("burn::tensor", "Int");
                self.import("burn::tensor", "TensorData");
                let values = self.indices(indices, shape[*dim]);
                format!(
                    "x.gather({dim}, Tensor::<4, Int>::from_data(TensorData::new({values}, {gathered:?}), device))"
                )
            }
            Op::Reshape(dims) => format!("x.reshape({dims:?})"),
            Op::Argmax { dim } => format!("x.argmax({dim}).float() * 0.1"),
        }
    }
}
